const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');
const env = require('../config/env');

// Ensure report storage directory exists
if (!fs.existsSync(env.REPORT_DIR)) {
  fs.mkdirSync(env.REPORT_DIR, { recursive: true });
}

function generateReportPDF(reportDoc, companyName, outputPath) {
  return new Promise((resolve, reject) => {
    try {
      const dir = path.dirname(outputPath);
      if (!fs.existsSync(dir)) {
        fs.mkdirSync(dir, { recursive: true });
      }

      const doc = new PDFDocument({
        size: 'A4',
        margin: 50,
        info: {
          Title: reportDoc.title,
          Author: 'CogniStock Enterprise System',
          Subject: reportDoc.type
        }
      });

      const writeStream = fs.createWriteStream(outputPath);
      doc.pipe(writeStream);

      // Header Palette: Dark slate / Indigo theme
      doc.rect(0, 0, 612, 85).fill('#0f172a');

      // Top Logo / Title
      doc.fillColor('#ffffff').fontSize(18).font('Helvetica-Bold')
        .text('CogniStock Intelligence System', 50, 25);
      doc.fillColor('#94a3b8').fontSize(9).font('Helvetica')
        .text('AI-Powered Demand Forecasting & Inventory Intelligence', 50, 48);

      // Company Badge on right
      doc.fillColor('#38bdf8').fontSize(11).font('Helvetica-Bold')
        .text(companyName.toUpperCase(), 350, 28, { align: 'right', width: 212 });
      doc.fillColor('#cbd5e1').fontSize(8).font('Helvetica')
        .text(`Ref: ${reportDoc._id.toString().slice(-8)} · ${new Date().toISOString().slice(0, 10)}`, 350, 44, { align: 'right', width: 212 });

      doc.moveDown(4);

      // Report Header Block
      doc.fillColor('#1e293b').fontSize(16).font('Helvetica-Bold')
        .text(reportDoc.title, 50, 110);
      doc.fillColor('#64748b').fontSize(10).font('Helvetica')
        .text(`Report Type: ${reportDoc.type} · Scope: ${reportDoc.skuScope || 'Catalog'} · Dataset: ${reportDoc.datasetVersion || 'v1.0'}`, 50, 132);

      // Horizontal line
      doc.strokeColor('#cbd5e1').lineWidth(1).moveTo(50, 150).lineTo(562, 150).stroke();

      // Executive Summary
      let y = 165;
      doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('1. Executive Summary', 50, y);
      y += 18;
      doc.fillColor('#334155').fontSize(9.5).font('Helvetica').lineGap(3)
        .text(reportDoc.executiveSummary || 'Analytical report automatically generated based on historical dataset ingestion, machine learning demand projection, and safety stock replenishment logic.', 50, y, { width: 512 });

      y = doc.y + 15;

      // Section 2: Key Metrics & Parameters
      doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('2. Core Findings & Parameters', 50, y);
      y += 20;

      const reportData = reportDoc.reportData || {};
      const params = [
        ['Target Dataset Version', reportDoc.datasetVersion || 'Nova Retail Demo v1.2'],
        ['Product Scope', reportDoc.skuScope || 'Full Catalog'],
        ['Generated By', reportDoc.generatedBy || 'Authorized Officer'],
        ['Execution Status', reportDoc.status || 'Ready'],
        ['Evaluated Models', 'Naive Baseline, ARIMA/SARIMA, XGBoost Regressor'],
        ['Recommendation Policy', 'Deterministic Safety Stock & Lead Time (DDLT + SS)']
      ];

      doc.fontSize(9).font('Helvetica');
      params.forEach(([label, val]) => {
        doc.rect(50, y, 512, 18).fillAndStroke(y % 36 === 0 ? '#f8fafc' : '#ffffff', '#e2e8f0');
        doc.fillColor('#475569').font('Helvetica-Bold').text(label, 60, y + 4, { width: 180 });
        doc.fillColor('#0f172a').font('Helvetica').text(String(val), 240, y + 4, { width: 310 });
        y += 18;
      });

      y += 20;

      // Section 3: Summary Table / Details if present
      if (reportData.items && Array.isArray(reportData.items) && reportData.items.length > 0) {
        doc.fillColor('#0f172a').fontSize(12).font('Helvetica-Bold').text('3. Detailed Catalog & Inventory Posture', 50, y);
        y += 20;

        // Table Header
        doc.rect(50, y, 512, 20).fill('#1e293b');
        doc.fillColor('#ffffff').fontSize(8).font('Helvetica-Bold');
        doc.text('SKU', 60, y + 6);
        doc.text('Product Name', 120, y + 6);
        doc.text('Stock', 260, y + 6);
        doc.text('Forecast 30d', 320, y + 6);
        doc.text('ROP', 400, y + 6);
        doc.text('Rec Qty', 460, y + 6);
        doc.text('Risk', 510, y + 6);

        y += 20;
        doc.font('Helvetica').fontSize(8);

        reportData.items.slice(0, 15).forEach((item) => {
          doc.rect(50, y, 512, 18).fillAndStroke(y % 36 === 0 ? '#f8fafc' : '#ffffff', '#e2e8f0');
          doc.fillColor('#0f172a').text(item.sku || 'N/A', 60, y + 5);
          doc.fillColor('#475569').text((item.name || '').substring(0, 24), 120, y + 5);
          doc.fillColor('#0f172a').text(String(item.currentStock ?? '-'), 260, y + 5);
          doc.fillColor('#b45309').text(String(item.forecastDemand30d ?? '-'), 320, y + 5);
          doc.fillColor('#6b21a8').text(String(item.reorderPoint ?? '-'), 400, y + 5);
          doc.fillColor('#047857').font('Helvetica-Bold').text(String(item.recommendedQty ?? '0'), 460, y + 5).font('Helvetica');
          doc.fillColor('#dc2626').text(item.riskLevel || 'Normal', 510, y + 5);
          y += 18;
        });

        if (reportData.items.length > 15) {
          doc.fillColor('#64748b').fontSize(7.5).font('Helvetica-Oblique')
            .text(`... and ${reportData.items.length - 15} additional catalog items recorded in database.`, 50, y + 4);
          y += 18;
        }
      }

      // Check if page needs a break for disclaimer
      if (y > 680) {
        doc.addPage();
        y = 50;
      } else {
        y += 15;
      }

      // Mandatory Disclaimer & Governance Notice
      doc.rect(50, y, 512, 60).fillAndStroke('#eff6ff', '#bfdbfe');
      doc.fillColor('#1e40af').fontSize(8.5).font('Helvetica-Bold')
        .text('COGNISTOCK DECISION-SUPPORT NOTICE', 60, y + 8);
      doc.fillColor('#1e3a8a').fontSize(7.5).font('Helvetica').lineGap(2)
        .text(
          'This document is an advisory decision-support report generated by CogniStock AI demand intelligence algorithms. ' +
          'CogniStock does not autonomously place purchase orders or transmit commitments to suppliers. ' +
          'All proposed reorder quantities and safety stock allocations require human officer review and signature before execution.',
          60, y + 22, { width: 492 }
        );

      // Footer
      const totalPages = doc.bufferedPageRange().count;
      for (let i = 0; i < totalPages; i++) {
        doc.switchToPage(i);
        doc.fillColor('#94a3b8').fontSize(7.5).font('Helvetica')
          .text(
            `CogniStock System Report · Generated for ${companyName} · Page ${i + 1} of ${totalPages}`,
            50, 780, { align: 'center', width: 512 }
          );
      }

      doc.end();

      writeStream.on('finish', () => resolve(outputPath));
      writeStream.on('error', (err) => reject(err));
    } catch (err) {
      reject(err);
    }
  });
}

module.exports = { generateReportPDF };
